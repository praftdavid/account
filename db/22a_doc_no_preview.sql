-- =====================================================================
-- 22a. 문서번호 변환 미리보기 (읽기만 한다 — 아무것도 바꾸지 않는다)
--   바뀔 번호를 "옛번호 → 새번호" 표로 보여준다. 표를 확인한 뒤 22b를 실행한다.
--   옛 양식  경영지원팀_202601   →   새 양식  프래프트(경영)2026-001
-- =====================================================================

SELECT doc_id,
       doc_no AS 옛번호,
       '프래프트(' || left(m[1], 2) || ')' || m[2] || '-' || lpad(m[3], 3, '0') AS 새번호
FROM (
  SELECT doc_id, doc_no, regexp_match(doc_no, '^(.+)_([0-9]{4})([0-9]+)$') AS m
  FROM documents
  WHERE doc_no IS NOT NULL
) t
WHERE m IS NOT NULL
ORDER BY 새번호;
