-- 프로젝트 업무종류(카테고리) — 사업계획/결산/총회/세무처럼 매년 정기적으로 반복되는
-- 업무 성격별로 분류해서, 연도와 상관없이 "이 종류 자료만" 검색해서 볼 수 있게 한다.
-- =====================================================================

ALTER TABLE projects ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT '기타'
    CHECK (category IN ('사업계획', '결산(가결산)', '총회', '세무', '기타'));
COMMENT ON COLUMN projects.category IS '업무종류 — 연도 필터와 별개로, 부서 내에서 이 값 하나로 전체 기간 검색 가능';
